-- 1. Create settlements/remittance batches table
CREATE TABLE IF NOT EXISTS public.settlement_batches (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id TEXT UNIQUE NOT NULL, -- e.g., BATCH-101
  dca_id TEXT NOT NULL, -- Links to DCA organization
  created_by UUID REFERENCES auth.users(id),
  
  -- Financial details
  total_amount NUMERIC NOT NULL DEFAULT 0,
  case_count INT NOT NULL DEFAULT 0,
  commission_rate NUMERIC DEFAULT 0.10, -- 10% default
  commission_amount NUMERIC DEFAULT 0,
  
  -- Bank transfer details
  utr_number TEXT, -- Bank transaction reference
  bank_name TEXT,
  proof_url TEXT, -- Uploaded screenshot/document
  
  -- Status tracking
  status TEXT DEFAULT 'PENDING', -- PENDING, SUBMITTED, VERIFIED, REJECTED
  fedex_verified_at TIMESTAMP,
  fedex_verified_by UUID,
  commission_status TEXT DEFAULT 'PENDING', -- PENDING, APPROVED, PAID
  
  -- Timestamps
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
  submitted_at TIMESTAMP WITH TIME ZONE,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- 2. Create case payments table (tracks individual payments from customers)
CREATE TABLE IF NOT EXISTS public.case_payments (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  case_id TEXT REFERENCES public.cases(case_id),
  
  -- Payment details
  payment_amount NUMERIC NOT NULL,
  payment_date DATE NOT NULL,
  payment_method TEXT, -- CASH, CHEQUE, BANK_TRANSFER, UPI, CARD
  reference_number TEXT, -- Cheque number or transaction ID
  
  -- Recording details
  recorded_by UUID REFERENCES auth.users(id), -- The agent who logged this
  dca_id TEXT NOT NULL,
  
  -- Settlement linking
  settlement_batch_id BIGINT REFERENCES public.settlement_batches(id),
  is_settled BOOLEAN DEFAULT false,
  settled_at TIMESTAMP,
  
  -- Status
  status TEXT DEFAULT 'UNSETTLED', -- UNSETTLED, BATCHED, SETTLED, DISPUTED
  
  -- Timestamps
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- 3. Enable RLS
ALTER TABLE public.settlement_batches ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.case_payments ENABLE ROW LEVEL SECURITY;

-- 4. RLS Policies for settlement_batches
-- FedEx Admin can see all
CREATE POLICY "FedEx Admin View All Settlements"
ON public.settlement_batches FOR SELECT
USING (
  (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'FEDEX_ADMIN'
);

-- DCA Manager can see their organization's settlements
CREATE POLICY "DCA Manager View Organization Settlements"
ON public.settlement_batches FOR SELECT
USING (
  dca_id = (SELECT organization_id FROM public.profiles WHERE id = auth.uid())
);

-- DCA Manager can create settlements for their organization
CREATE POLICY "DCA Manager Create Settlements"
ON public.settlement_batches FOR INSERT
WITH CHECK (
  (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'DCA_MANAGER'
  AND dca_id = (SELECT organization_id FROM public.profiles WHERE id = auth.uid())
);

-- DCA Manager can update their settlements
CREATE POLICY "DCA Manager Update Settlements"
ON public.settlement_batches FOR UPDATE
USING (
  dca_id = (SELECT organization_id FROM public.profiles WHERE id = auth.uid())
);

-- FedEx Admin can update all settlements (for verification)
CREATE POLICY "FedEx Admin Update All Settlements"
ON public.settlement_batches FOR ALL
USING (
  (SELECT role FROM public.profiles WHERE id = auth.uid()) = 'FEDEX_ADMIN'
);

