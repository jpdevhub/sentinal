INSERT INTO public.case_payments (case_id, payment_amount, payment_date, payment_method, reference_number, recorded_by, dca_id, status)
SELECT 
  c.case_id,
  ROUND((c.amount_recovered * 0.3 + RANDOM() * c.amount_recovered * 0.2)::numeric, 2) as payment_amount,
  (CURRENT_DATE - (RANDOM() * 30)::int) as payment_date,
  (ARRAY['BANK_TRANSFER', 'CHEQUE', 'UPI', 'CASH', 'CARD'])[FLOOR(RANDOM() * 5 + 1)] as payment_method,
  CASE 
    WHEN RANDOM() > 0.5 THEN 'REF-' || FLOOR(RANDOM() * 1000000)::text
    ELSE 'CHQ-' || FLOOR(RANDOM() * 100000)::text
  END as reference_number,
  (SELECT id FROM public.profiles WHERE organization_id = c.dca_id AND role = 'DCA_AGENT' LIMIT 1) as recorded_by,
  c.dca_id,
  'UNSETTLED'
FROM public.cases c
WHERE c.amount_recovered > 0 
  AND c.case_status IN ('PAID', 'IN_PROGRESS')
  AND c.dca_id = 'DCA_A' -- Only for DCA_A to match our test user
LIMIT 60;

